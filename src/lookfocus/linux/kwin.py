"""The KWin bridge: a KWin script that is LookFocus's eyes and hands in the window manager.

On Wayland no ordinary client can list other windows, see which one is active, read the pointer position
or activate a window. KWin scripts can (they run inside the compositor), and KWin loads them over DBus
(org.kde.kwin.Scripting). So this module writes a small script, loads it, and talks to it over the session
bus, where this process is the server:

- script -> LookFocus: `Event(kind, json)` calls: "hello", "active" (windowActivated), "cursor" (pointer
  moved, throttled to one per CURSOR_MS), "screens_changed", "desktop_changed", "hotkey", "reply", "log".
- LookFocus -> script: the script keeps one `Next()` call pending; LookFocus answers it with a JSON batch of
  commands ("windows", "screens", "activate", "cursor", "quit") and the script calls Next() again. KWin's
  callDBus is asynchronous, so the pending call never blocks the compositor. An idle Next() is answered
  with an empty batch every KEEPALIVE_S, well inside DBus's 25 s default timeout.

The script is addressed to this process's unique bus name and named after the pid, so several LookFocus
processes (the tray and a `lookfocus watch` in a terminal) each get their own. Scripts left behind by a
crashed process are unloaded on the next start (their pid is in the file name). Only the tray app registers
the pause shortcut (registerShortcut: a KDE global shortcut owned by KWin, not a key hook).

Measured on Plasma 6.8.2: the script runs ~8 ms after loadScript, and a command round trip takes ~1 ms.
"""

from __future__ import annotations

import atexit
import itertools
import json
import logging
import os
import threading
import time
from collections.abc import Callable
from pathlib import Path
from queue import Empty, Queue

from jeepney import DBusAddress, MatchRule, MessageType, new_error, new_method_call, new_method_return
from jeepney.io.threading import DBusRouter, open_dbus_connection
from jeepney.low_level import HeaderFields

log = logging.getLogger(__name__)

PATH = "/lookfocus"
IFACE = "org.lookfocus.Bridge"
KEEPALIVE_S = 10.0
CURSOR_MS = 30
SHORTCUT_NAME = "LookFocus: pause or resume"
SCRIPTING = DBusAddress("/Scripting", bus_name="org.kde.KWin", interface="org.kde.kwin.Scripting")

Listener = Callable[[str, dict], None]


class BridgeError(RuntimeError):
    pass


NOT_KDE = (
    "LookFocus on Linux needs KDE Plasma 6 on Wayland: it moves focus through a KWin script, and this "
    "session has no KWin scripting service ({why})"
)

SCRIPT = r"""
// LookFocus KWin bridge (generated by lookfocus/linux/kwin.py; unloaded when LookFocus exits).
var BUS = "@BUS@", PATH = "@PATH@", IFACE = "@IFACE@", HOTKEY = "@HOTKEY@", CURSOR_MS = @CURSOR_MS@;

function send(kind, data) {
  callDBus(BUS, PATH, IFACE, "Event", kind, JSON.stringify(data === undefined ? {} : data));
}
function wid(w) { return w ? String(w.internalId) : null; }
function rootOf(w) {
  for (var n = 0; w && w.transient && w.transientFor && n < 10; n++) w = w.transientFor;
  return w;
}
function onCurrentDesktop(w) {
  if (!w.onAllDesktops) {
    var cur = workspace.currentDesktop, ds = w.desktops || [], ok = false;
    for (var i = 0; i < ds.length; i++) if (ds[i] === cur || (cur && ds[i].id === cur.id)) ok = true;
    if (!ok) return false;
  }
  var acts = w.activities || [], act = workspace.currentActivity;
  return !(acts.length && act && acts.indexOf(act) < 0);
}
function info(w) {
  var g = w.frameGeometry;
  return {
    id: wid(w), root: wid(rootOf(w)), caption: w.caption, cls: w.resourceClass, app: w.resourceName,
    pid: w.pid, x: g.x, y: g.y, w: g.width, h: g.height, minimized: w.minimized, normal: w.normalWindow,
    dialog: w.dialog, modal: w.modal, transient: w.transient, special: w.specialWindow,
    desktopWindow: w.desktopWindow, dock: w.dock, popup: w.popupWindow, skipSwitcher: w.skipSwitcher,
    managed: w.managed, deleted: w.deleted, hidden: w.hidden, onCurrentDesktop: onCurrentDesktop(w)
  };
}
function windows() {
  // stackingOrder is bottom to top
  var out = [], st = workspace.stackingOrder;
  for (var i = 0; i < st.length; i++) if (st[i].managed && !st[i].deleted) out.push(info(st[i]));
  return {active: wid(workspace.activeWindow), windows: out};
}
function screens() {
  var order = [], out = [];
  for (var i = 0; i < workspace.screenOrder.length; i++) order.push(workspace.screenOrder[i].name);
  for (var j = 0; j < workspace.screens.length; j++) {
    var s = workspace.screens[j], g = s.geometry;
    out.push({name: s.name, x: g.x, y: g.y, w: g.width, h: g.height, scale: s.devicePixelRatio,
              manufacturer: s.manufacturer, model: s.model, serial: s.serialNumber});
  }
  return {order: order, screens: out};
}
function find(id) {
  var ws = workspace.windowList();
  for (var i = 0; i < ws.length; i++) if (wid(ws[i]) === id) return ws[i];
  return null;
}
function activate(id) {
  var w = find(id);
  if (!w || w.deleted) return {ok: false, reason: "window no longer exists"};
  // A modal dialog of the window takes the focus instead (as Windows' GetLastActivePopup does).
  var target = w, st = workspace.stackingOrder;
  for (var i = st.length - 1; i >= 0; i--) {
    var c = st[i];
    if (c !== w && c.modal && !c.minimized && !c.deleted && rootOf(c) === w) { target = c; break; }
  }
  workspace.activeWindow = target;
  var a = workspace.activeWindow;
  return {ok: !!a && rootOf(a) === rootOf(w), active: wid(a), target: wid(target)};
}
function handle(cmd) {
  var r;
  if (cmd.op === "windows") r = windows();
  else if (cmd.op === "screens") r = screens();
  else if (cmd.op === "activate") r = activate(cmd.id);
  else if (cmd.op === "cursor") r = {x: workspace.cursorPos.x, y: workspace.cursorPos.y};
  else r = {error: "unknown op " + cmd.op};
  send("reply", {req: cmd.req, result: r});
}
function poll() {
  callDBus(BUS, PATH, IFACE, "Next", function (text) {
    var cmds;
    try { cmds = JSON.parse(text); } catch (e) { send("log", {msg: "bad batch: " + e}); cmds = []; }
    for (var i = 0; i < cmds.length; i++) {
      if (cmds[i].op === "quit") return;
      try { handle(cmds[i]); } catch (e) { send("reply", {req: cmds[i].req, result: {error: String(e)}}); }
    }
    poll();
  });
}
workspace.windowActivated.connect(function (w) { send("active", {id: wid(w), root: wid(rootOf(w))}); });
var lastCursor = 0;
workspace.cursorPosChanged.connect(function () {
  var now = Date.now();
  if (now - lastCursor < CURSOR_MS) return;
  lastCursor = now;
  var p = workspace.cursorPos;
  send("cursor", {x: p.x, y: p.y});
});
workspace.screensChanged.connect(function () { send("screens_changed"); });
workspace.currentDesktopChanged.connect(function () { send("desktop_changed"); });
if (HOTKEY) registerShortcut("@SHORTCUT@", "@SHORTCUT@", HOTKEY, function () { send("hotkey"); });
var p0 = workspace.cursorPos;
send("hello", {version: 1, cursor: {x: p0.x, y: p0.y}, active: wid(workspace.activeWindow)});
poll();
"""


def _js_string(s: str) -> str:
    return json.dumps(s)[1:-1]


def render_script(bus_name: str, hotkey: str = "") -> str:
    """The script text for this process (pure; unit tested)."""
    out = SCRIPT
    for key, value in {
        "@BUS@": _js_string(bus_name),
        "@PATH@": PATH,
        "@IFACE@": IFACE,
        "@HOTKEY@": _js_string(hotkey),
        "@SHORTCUT@": _js_string(SHORTCUT_NAME),
        "@CURSOR_MS@": str(CURSOR_MS),
    }.items():
        out = out.replace(key, value)
    return out


def runtime_dir() -> Path:
    base = os.environ.get("XDG_RUNTIME_DIR") or f"/tmp/lookfocus-{os.getuid()}"
    d = Path(base) / "lookfocus"
    d.mkdir(mode=0o700, parents=True, exist_ok=True)
    return d


def _pid_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


class KWinBridge:
    def __init__(self, hotkey: str = "") -> None:
        self.hotkey = hotkey
        self.plugin = f"lookfocus-{os.getpid()}"
        self.cursor: tuple[int, int] = (0, 0)
        self.active: str | None = None  # root window id of the active window
        self._router: DBusRouter | None = None
        self._filter = None
        self._queue: Queue = Queue()
        self._lock = threading.Lock()
        self._pending = None  # the script's outstanding Next() call
        self._pending_since = 0.0
        self._outbox: list[dict] = []
        self._replies: dict[int, tuple[threading.Event, list]] = {}
        self._req = itertools.count(1)
        self._listeners: list[Listener] = []
        self._hello = threading.Event()
        self._halt = threading.Event()
        self._thread: threading.Thread | None = None
        self._script_path: Path | None = None

    # --- lifecycle ------------------------------------------------------------------------------
    def start(self, timeout: float = 3.0) -> None:
        try:
            conn = open_dbus_connection("SESSION")
        except Exception as e:
            raise BridgeError(NOT_KDE.format(why=f"no session bus: {e}")) from e
        self._router = DBusRouter(conn)
        rule = MatchRule(type="method_call", path=PATH, interface=IFACE)
        self._filter = self._router.filter(rule, queue=self._queue)
        self._thread = threading.Thread(target=self._serve, name="kwin-bridge", daemon=True)
        self._thread.start()
        try:
            self._cleanup_stale()
            self._call(SCRIPTING, "unloadScript", "s", (self.plugin,))
            path = runtime_dir() / f"kwin-{os.getpid()}.js"
            path.write_text(render_script(self._router.unique_name, self.hotkey), encoding="utf-8")
            self._script_path = path
            (script_id,) = self._call(SCRIPTING, "loadScript", "ss", (str(path), self.plugin))
            if script_id < 0:
                raise BridgeError(f"KWin refused to load {path}")
            script = DBusAddress(
                f"/Scripting/Script{script_id}", bus_name="org.kde.KWin", interface="org.kde.kwin.Script"
            )
            self._call(script, "run")
        except BridgeError:
            self.stop()
            raise
        except Exception as e:
            self.stop()
            raise BridgeError(NOT_KDE.format(why=f"{type(e).__name__}: {e}")) from e
        if not self._hello.wait(timeout):
            self.stop()
            raise BridgeError("the KWin script loaded but never reported back (is KWin scripting disabled?)")
        log.info("KWin bridge running (script %s, bus name %s)", self.plugin, self._router.unique_name)

    def stop(self) -> None:
        if self._halt.is_set():
            return
        self._halt.set()
        with self._lock:
            self._outbox = [{"op": "quit"}]
            self._flush_locked()
        if self._router is not None:
            try:
                self._call(SCRIPTING, "unloadScript", "s", (self.plugin,), timeout=1.0)
            except Exception as e:
                log.debug("unloadScript failed: %s", e)
        if self._script_path is not None:
            self._script_path.unlink(missing_ok=True)
        if self._filter is not None:
            self._filter.close()
        if self._router is not None:
            self._router.close()
            self._router.conn.close()
            self._router = None
        for ev, _box in list(self._replies.values()):
            ev.set()

    def _cleanup_stale(self) -> None:
        """Unload scripts of LookFocus processes that died without unloading theirs."""
        for f in runtime_dir().glob("kwin-*.js"):
            try:
                pid = int(f.stem.split("-", 1)[1])
            except ValueError:
                continue
            if pid != os.getpid() and not _pid_alive(pid):
                try:
                    self._call(SCRIPTING, "unloadScript", "s", (f"lookfocus-{pid}",), timeout=1.0)
                    log.info("unloaded a stale KWin script from pid %d", pid)
                except Exception as e:
                    log.debug("stale script %d: %s", pid, e)
                f.unlink(missing_ok=True)

    def _call(self, addr: DBusAddress, method: str, sig: str | None = None, body=(), timeout: float = 3.0):
        assert self._router is not None
        msg = new_method_call(addr, method, sig, body) if sig else new_method_call(addr, method)
        reply = self._router.send_and_get_reply(msg, timeout=timeout)
        if reply.header.message_type == MessageType.error:
            raise BridgeError(f"{method}: {reply.header.fields.get(HeaderFields.error_name)} {reply.body}")
        return reply.body

    # --- API ------------------------------------------------------------------------------------
    @property
    def running(self) -> bool:
        return self._hello.is_set() and not self._halt.is_set()

    def add_listener(self, fn: Listener) -> None:
        with self._lock:
            self._listeners.append(fn)

    def remove_listener(self, fn: Listener) -> None:
        with self._lock:
            if fn in self._listeners:
                self._listeners.remove(fn)

    def request(self, op: str, timeout: float = 2.0, **args) -> dict:
        """Run one command in the script and return its result (raises BridgeError on failure)."""
        if self._halt.is_set():
            raise BridgeError("KWin bridge stopped")
        req = next(self._req)
        ev, box = threading.Event(), []
        with self._lock:
            self._replies[req] = (ev, box)
            self._outbox.append({"req": req, "op": op, **args})
            if self._pending is not None:
                self._flush_locked()
        try:
            if not ev.wait(timeout) or not box:
                raise BridgeError(f"KWin script didn't answer {op!r} within {timeout:.1f}s")
        finally:
            with self._lock:
                self._replies.pop(req, None)
        result = box[0]
        if isinstance(result, dict) and "error" in result:
            raise BridgeError(f"KWin script: {result['error']}")
        return result

    # --- serving the script ---------------------------------------------------------------------
    def _flush_locked(self) -> None:
        if self._pending is None or self._router is None:
            return
        batch, self._outbox = self._outbox, []
        msg, self._pending = self._pending, None
        try:
            self._router.send(new_method_return(msg, "s", (json.dumps(batch),)))
        except Exception as e:
            log.warning("couldn't send commands to the KWin script: %s", e)

    def _serve(self) -> None:
        while not self._halt.is_set():
            try:
                msg = self._queue.get(timeout=1.0)
            except Empty:
                msg = None
            if msg is not None:
                try:
                    self._handle(msg)
                except Exception:
                    log.exception("KWin bridge message failed")
            with self._lock:
                if self._pending is not None and time.monotonic() - self._pending_since > KEEPALIVE_S:
                    self._flush_locked()

    def _handle(self, msg) -> None:
        member = msg.header.fields.get(HeaderFields.member)
        if member == "Next":
            with self._lock:
                if self._pending is not None:  # shouldn't happen; release the older one
                    self._router.send(new_method_return(self._pending, "s", ("[]",)))
                self._pending, self._pending_since = msg, time.monotonic()
                if self._outbox:
                    self._flush_locked()
            return
        if member != "Event":
            self._router.send(new_error(msg, "org.freedesktop.DBus.Error.UnknownMethod", "s", (str(member),)))
            return
        self._router.send(new_method_return(msg))
        kind, text = msg.body
        data = json.loads(text) if text else {}
        if kind == "reply":
            with self._lock:
                waiter = self._replies.get(data.get("req"))
            if waiter is not None:
                waiter[1].append(data.get("result"))
                waiter[0].set()
            return
        if kind == "cursor":
            self.cursor = (round(data["x"]), round(data["y"]))
        elif kind == "active":
            self.active = data.get("root")
        elif kind == "hello":
            c = data.get("cursor") or {}
            self.cursor = (round(c.get("x", 0)), round(c.get("y", 0)))
            self.active = data.get("active")
            self._hello.set()
            return
        elif kind == "log":
            log.info("KWin script: %s", data.get("msg"))
            return
        with self._lock:
            listeners = list(self._listeners)
        for fn in listeners:
            try:
                fn(kind, data)
            except Exception:
                log.exception("KWin bridge listener failed")


_bridge: KWinBridge | None = None
_bridge_lock = threading.Lock()
_hotkey = ""


def configure(hotkey: str) -> None:
    """Before the first get_bridge(): the KDE key sequence for the pause shortcut (tray app only)."""
    global _hotkey
    _hotkey = hotkey


def get_bridge() -> KWinBridge:
    """The process's bridge, started on first use (raises BridgeError outside KDE Plasma on Wayland)."""
    global _bridge
    with _bridge_lock:
        if _bridge is None or _bridge._halt.is_set():
            b = KWinBridge(_hotkey)
            b.start()
            _bridge = b
            atexit.register(b.stop)
        return _bridge


def shutdown() -> None:
    global _bridge
    with _bridge_lock:
        if _bridge is not None:
            _bridge.stop()
            _bridge = None
